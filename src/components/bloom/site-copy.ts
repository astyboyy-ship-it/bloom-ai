const COPY: Record<Lang, SiteCopy> = { en, es, he };

/** The site copy for the visitor's language. */
export function useSiteCopy() {
  const { lang, dir } = useI18n();
  return { lang, dir, s: COPY[lang] };
}

/** The engine with its descriptive text in the given language; name, slug, icons and links are unchanged. */
export function localizeSiteEngine(e: Engine, lang: Lang): Engine {
  const tx = COPY[lang].engines?.[e.slug];
  if (!tx) return e;
  return {
    ...e,
    subtitle: tx.subtitle,
    teaser: tx.teaser,
    description: tx.description,
    build: tx.build,
    testing: tx.testing,
    access: tx.access,
    aware: { senses: tx.senses, perceive: tx.perceive, reason: tx.reason, execute: tx.execute },
    pathways: e.pathways.map((p, i) => ({ label: tx.pathways[i]?.[0] ?? p.label, audience: tx.pathways[i]?.[1] ?? p.audience })),
    services: e.services.map((sv, i) => ({ ...sv, label: tx.services[i] ?? sv.label })),
    cta: tx.cta,
    widgetLabel: tx.widgetLabel,
  };
}
