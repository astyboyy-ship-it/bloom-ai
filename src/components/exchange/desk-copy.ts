export const DESK_DICTS = { en, es } satisfies Record<ExchangeLang, Dict>;
export type DeskCopy = Dict;

/** The Exchange's language: English unless the site language is Spanish. */
export function useExchangeLang(): { lang: ExchangeLang; setLang: (l: ExchangeLang) => void } {
  const { lang, setLang } = useI18n();
  return { lang: lang === "es" ? "es" : "en", setLang };
}

export const useDeskCopy = () => DESK_DICTS[useExchangeLang().lang];
